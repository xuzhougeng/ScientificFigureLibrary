#!/usr/bin/env node
// Generate the user-guide figure indexes from bundled catalog metadata.
// Outputs four Markdown pages under docs/generated/ (zh-CN and English, for
// Open Figure Modules and FigureYa). Deterministic: no wall-clock timestamps,
// sorted output, so re-running on unchanged catalogs yields identical bytes.
// Missing metadata and missing preview/thumbnail files are marked honestly.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(repoRoot, "docs", "generated");

const ofmCatalog = JSON.parse(
  fs.readFileSync(path.join(repoRoot, "assets", "personal-modules", "module-catalog.json"), "utf8"),
);
const figureyaCatalog = JSON.parse(
  fs.readFileSync(path.join(repoRoot, "assets", "catalog.json"), "utf8"),
);

function exists(relativePath) {
  return fs.existsSync(path.join(repoRoot, relativePath));
}

function cell(text) {
  return String(text ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function firstLine(text) {
  return String(text ?? "").split(/\r?\n/, 1)[0].trim();
}

function truncate(text, max) {
  const line = firstLine(text);
  return line.length > max ? `${line.slice(0, max)}…` : line;
}

const GENERATED_NOTE_ZH =
  "<!-- 本文件由 scripts/build-user-guide-index.mjs 从仓库内置目录元数据自动生成,请勿手工编辑。重新生成:npm run docs:index -->";
const GENERATED_NOTE_EN =
  "<!-- Generated by scripts/build-user-guide-index.mjs from the bundled catalog metadata. Do not edit by hand. Regenerate with: npm run docs:index -->";

// ---------------------------------------------------------------------------
// Open Figure Modules index
// ---------------------------------------------------------------------------

function ofmPreviewLink(mod, lang) {
  const previewPath = mod.preview?.path
    ? path.posix.join("assets/personal-modules", mod.preview.path)
    : null;
  if (previewPath && exists(previewPath)) {
    const href = path.posix.join("..", "..", "assets", "personal-modules", mod.preview.path);
    return lang === "zh" ? `[预览图](${href})` : `[Preview](${href})`;
  }
  return lang === "zh" ? "预览文件缺失" : "preview file missing";
}

function ofmThumbLink(mod, lang) {
  const thumbPath = mod.thumbnail?.path
    ? path.posix.join("assets/personal-modules", mod.thumbnail.path)
    : null;
  if (thumbPath && exists(thumbPath)) {
    const href = path.posix.join("..", "..", "assets", "personal-modules", mod.thumbnail.path);
    return lang === "zh" ? `[缩略图](${href})` : `[Thumbnail](${href})`;
  }
  return lang === "zh" ? "缩略图缺失" : "thumbnail missing";
}

function ofmModule(mod, lang) {
  const t = lang === "zh";
  const title = t ? `${mod.title}（${mod.titleEn}）` : `${mod.titleEn}（${mod.title}）`;
  const lines = [];
  lines.push(`#### ${title}`);
  lines.push("");
  lines.push(
    t
      ? `**稳定标识:** \`${mod.moduleId}\` · **分类:** \`${mod.plotFamily}\` · **语言:** ${cell(mod.language ?? "未记录")}`
      : `**Stable ID:** \`${mod.moduleId}\` · **Plot family:** \`${mod.plotFamily}\` · **Language:** ${cell(mod.language ?? "not recorded")}`,
  );
  lines.push("");
  lines.push(
    `${ofmPreviewLink(mod, lang)} · ${ofmThumbLink(mod, lang)} · [${t ? "模块源码" : "Module source"}](https://github.com/${mod.source.repository}/tree/${mod.source.commit}/${mod.source.path})`,
  );
  lines.push("");
  lines.push(
    `- **${t ? "适用科研场景" : "Research use"}:** ${cell(mod.application || (t ? "未记录" : "not recorded"))}`,
  );
  const inputFiles = (mod.inputFiles ?? []).filter(Boolean);
  const inputs = t
    ? `${cell(mod.dataProfile || "未记录")}${inputFiles.length ? `（${t ? "示例输入" : "example inputs"}: \`${inputFiles.join("\`, \`")}\`）` : ""}`
    : `${cell(mod.dataProfile || "not recorded")}${inputFiles.length ? ` (example inputs: \`${inputFiles.join("\`, \`")}\`)` : ""}`;
  lines.push(`- **${t ? "输入数据要求" : "Input data"}:** ${inputs}`);
  const lic = mod.licenses ?? {};
  lines.push(
    t
      ? `- **来源与许可:** ${mod.source.repository}（Open Figure Modules 官方频道);代码 ${cell(lic.code ?? "未记录")},内容 ${cell(lic.content ?? "未记录")},文档 ${cell(lic.documentation ?? "未记录")}`
      : `- **Source and license:** ${mod.source.repository} (official Open Figure Modules channel); code ${cell(lic.code ?? "not recorded")}, content ${cell(lic.content ?? "not recorded")}, documentation ${cell(lic.documentation ?? "not recorded")}`,
  );
  const provenance = (mod.provenance ?? []).find((p) => p?.type === "module_execution_check");
  const exec = mod.publisher?.executionScope
    ? `${mod.publisher.executionScope} / ${mod.publisher.executionStatus ?? (t ? "未记录" : "not recorded")}`
    : provenance
      ? truncate(provenance.note ?? "", 160)
      : t
        ? "未记录"
        : "not recorded";
  lines.push(
    t
      ? `- **可复现性记录:** ${cell(exec)};完整模块 ZIP 仅在通过 SFL materialize 获取时下载校验`
      : `- **Reproducibility record:** ${cell(exec)}; the complete module ZIP is only downloaded and verified through an SFL materialization`,
  );
  lines.push("");
  lines.push(t ? "调用示例(复制后替换路径):" : "Invocation example (copy and adjust the path):");
  lines.push("");
  lines.push("```text");
  if (t) {
    lines.push(
      `在 Scientific Figure Library 中搜索模板 "${mod.moduleId}"(来源 Open Figure Modules)。`,
      "先给我预览,等我确认这张卡之后,再把该模板 materialize 到我指定的空文件夹,文件集用 template。",
      "不要执行绘图代码;先和我确认数据怎么替换成我自己的。",
    );
  } else {
    lines.push(
      `Search Scientific Figure Library for the template "${mod.moduleId}" (Open Figure Modules).`,
      "Show me the preview first; after I confirm that exact card, materialize it into an empty folder I specify, using the template file set.",
      "Do not execute plotting code; discuss with me how to swap in my own data first.",
    );
  }
  lines.push("```");
  lines.push("");
  return lines.join("\n");
}

function buildOfmIndex(lang) {
  const t = lang === "zh";
  const mods = [...ofmCatalog.modules].sort((a, b) => a.moduleId.localeCompare(b.moduleId));
  const families = [...new Set(mods.map((m) => m.plotFamily))].sort();
  const commits = [...new Set(mods.map((m) => m.source.commit))].sort();
  const missingPreview = mods.filter((m) => !ofmPreviewLink(m, lang).includes("](")).length;
  const out = [];
  out.push(t ? GENERATED_NOTE_ZH : GENERATED_NOTE_EN);
  out.push("");
  out.push(
    t
      ? "# 图型索引:Open Figure Modules(自动生成)"
      : "# Figure index: Open Figure Modules (auto-generated)",
  );
  out.push("");
  out.push(
    t
      ? `[返回用户手册目录](../USER_GUIDE.zh-CN.md#4-图型索引按用途) · [返回本页目录](#目录)`
      : `[Back to the user guide](../USER_GUIDE.md#4-figure-index-by-purpose) · [Back to this page's TOC](#table-of-contents)`,
  );
  out.push("");
  out.push(t ? "## 快照信息" : "## Snapshot");
  out.push("");
  out.push(
    t
      ? `- 目录 schema:\`${ofmCatalog.schema}\``
      : `- Catalog schema: \`${ofmCatalog.schema}\``,
  );
  out.push(
    t
      ? `- Provider:\`${ofmCatalog.provider.providerId}\`(${ofmCatalog.provider.displayName})`
      : `- Provider: \`${ofmCatalog.provider.providerId}\` (${ofmCatalog.provider.displayName})`,
  );
  out.push(
    t
      ? `- 内容仓库:[${ofmCatalog.provider.repository}](https://github.com/${ofmCatalog.provider.repository})`
      : `- Content repository: [${ofmCatalog.provider.repository}](https://github.com/${ofmCatalog.provider.repository})`,
  );
  out.push(
    t
      ? `- 模块数量:${mods.length};覆盖的源 commit:${commits.map((c) => `\`${c.slice(0, 12)}\``).join("、")}`
      : `- Modules: ${mods.length}; source commits covered: ${commits.map((c) => `\`${c.slice(0, 12)}\``).join(", ")}`,
  );
  out.push(
    t
      ? `- 元数据完整性:${missingPreview === 0 ? "全部条目均有可用的预览图与缩略图文件" : `${missingPreview} 个条目缺少预览/缩略图文件,已在条目中如实标注`}`
      : `- Metadata completeness: ${missingPreview === 0 ? "every entry has an available preview and thumbnail file" : `${missingPreview} entries lack preview/thumbnail files and are marked honestly below`}`,
  );
  out.push("");
  out.push(
    t
      ? "> 本页由内置目录快照生成。插件安装后会通过签名 feed 异步更新本地 overlay,远端可能已有新增或下架模块;以 SFL 搜索结果为准。"
      : "> This page is generated from the bundled catalog snapshot. After install, SFL refreshes the local overlay through a signed feed, so the remote may already contain newer or retired modules; always trust the SFL search results.",
  );
  out.push("");
  out.push(t ? "## 目录" : "## Table of contents");
  out.push("");
  for (const family of families) {
    const count = mods.filter((m) => m.plotFamily === family).length;
    out.push(`- [\`${family}\`](#${family})(${count})`);
  }
  out.push("");
  out.push(t ? "---" : "---");
  out.push("");
  for (const family of families) {
    out.push(`### ${family}`);
    out.push("");
    for (const mod of mods.filter((m) => m.plotFamily === family)) {
      out.push(ofmModule(mod, lang));
    }
  }
  out.push(
    t
      ? `[返回用户手册目录](../USER_GUIDE.zh-CN.md#4-图型索引按用途) · [返回本页目录](#目录)`
      : `[Back to the user guide](../USER_GUIDE.md#4-figure-index-by-purpose) · [Back to this page's TOC](#table-of-contents)`,
  );
  out.push("");
  return out.join("\n");
}

