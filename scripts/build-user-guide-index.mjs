function figureyaRows(lang) {
  const t = lang === "zh";
  const mods = [...figureyaCatalog.modules].sort((a, b) => a.moduleId.localeCompare(b.moduleId));
  const rows = [];
  for (const mod of mods) {
    const id = `\`${mod.moduleId}\``;
    let thumb = t ? "未收录" : "none bundled";
    if (mod.thumbnail) {
      const assetPath = path.posix.join("assets", mod.thumbnail);
      if (exists(assetPath)) {
        const href = path.posix.join("..", "..", "assets", mod.thumbnail);
        thumb = t ? `[缩略图](${href})` : `[thumbnail](${href})`;
      } else {
        thumb = t ? "缩略图文件缺失" : "thumbnail file missing";
      }
    }
    const packages = (mod.packages ?? []).filter(Boolean);
    const inputs = (mod.inputFiles ?? []).filter(Boolean);
    const inputCell = inputs.length
      ? `\`${inputs[0]}\`${inputs.length > 1 ? (t ? ` 等 ${inputs.length} 个` : ` +${inputs.length - 1}`) : ""}`
      : t
        ? "未记录"
        : "not recorded";
    const description = truncate(
      mod.application || mod.requirement || mod.inputSummary || "",
      110,
    );
    const descCell = description || (t ? "未记录" : "not recorded");
    const report =
      mod.reportUrl && /^https:\/\//.test(mod.reportUrl)
        ? t
          ? `[在线报告](${mod.reportUrl})`
          : `[report](${mod.reportUrl})`
        : "—";
    rows.push(
      `| ${id} | ${thumb} | ${packages.length ? cell(packages.join(", ")) : t ? "未记录" : "not recorded"} | ${inputCell} | ${cell(descCell)} | ${report} |`,
    );
  }
  return rows;
}

function buildFigureyaIndex(lang) {
  const t = lang === "zh";
  const mods = [...figureyaCatalog.modules].sort((a, b) => a.moduleId.localeCompare(b.moduleId));
  const count = (field) => mods.filter((m) => m[field]).length;
  const rows = figureyaRows(lang);
  const out = [];
  out.push(t ? GENERATED_NOTE_ZH : GENERATED_NOTE_EN);
  out.push("");
  out.push(
    t
      ? "# 图型索引:FigureYa 模板(自动生成)"
      : "# Figure index: FigureYa templates (auto-generated)",
  );
  out.push("");
  out.push(
    t
      ? `[返回用户手册目录](../USER_GUIDE.zh-CN.md#4-图型索引按用途) · [返回本页目录](#目录)`
      : `[Back to the user guide](../USER_GUIDE.md#4-figure-index-by-purpose) · [Back to this page's TOC](#table-of-contents)`,
  );
  out.push("");
  out.push(t ? "## 快照信息" : "## Snapshot");
  out.push("");
  out.push(t ? `- 目录 schema:\`${figureyaCatalog.schema}\`` : `- Catalog schema: \`${figureyaCatalog.schema}\``);
  out.push(
    t
      ? `- 上游仓库:[ying-ge/FigureYa](https://github.com/ying-ge/FigureYa) @ \`${figureyaCatalog.figureya.commit.slice(0, 12)}\`(压缩版 [ying-ge/FigureYa-compressed](https://github.com/ying-ge/FigureYa-compressed) @ \`${figureyaCatalog.compressed.commit.slice(0, 12)}\`)`
      : `- Upstream repository: [ying-ge/FigureYa](https://github.com/ying-ge/FigureYa) @ \`${figureyaCatalog.figureya.commit.slice(0, 12)}\` (compressed copy [ying-ge/FigureYa-compressed](https://github.com/ying-ge/FigureYa-compressed) @ \`${figureyaCatalog.compressed.commit.slice(0, 12)}\`)`,
  );
  out.push(t ? `- 目录生成时间:${figureyaCatalog.generatedAt}` : `- Catalog generated at: ${figureyaCatalog.generatedAt}`);
  out.push(
    t
      ? `- 模板数量:${mods.length};含缩略图 ${count("thumbnail")}、在线报告链接 ${count("reportUrl")}、应用场景 ${count("application")}、输入说明 ${count("inputSummary")}。缺失字段在表中如实标注为"未记录"。`
      : `- Templates: ${mods.length}; with thumbnail ${count("thumbnail")}, with report link ${count("reportUrl")}, with use case ${count("application")}, with input notes ${count("inputSummary")}. Missing fields are marked honestly as "not recorded".`,
  );
  out.push(
    t
      ? "- 许可:FigureYa 上游内容采用 CC BY-NC-SA 4.0(见 `assets/FIGUREYA_LICENSE.txt`);引用信息见下方说明。"
      : "- License: the upstream FigureYa content is CC BY-NC-SA 4.0 (see `assets/FIGUREYA_LICENSE.txt`); citation below.",
  );
  out.push(
    t
      ? `- 引用:${cell(figureyaCatalog.citation)}`
      : `- Citation: ${cell(figureyaCatalog.citation)}`,
  );
  out.push("");
  out.push(
    t
      ? "> FigureYa 目录没有按用途的分类元数据,本页按模板 ID 字母序列出全部模板,描述文字摘录自上游双语文档,未做改写。想按场景找图时,建议直接在 SFL 里用关键词搜索(如 survival、PCA、 volcano)。"
      : "> The FigureYa catalog carries no use-case categories, so this page lists every template by ID in alphabetical order; descriptions are quoted from the upstream bilingual docs without rewriting. To find a figure by scenario, search by keyword in SFL instead (for example survival, PCA, volcano).",
  );
  out.push("");
  out.push(t ? "## 目录" : "## Table of contents");
  out.push("");
  out.push(
    t
      ? "- [快照信息](#快照信息)\n- [调用示例(复制后替换模板 ID)](#调用示例复制后替换模板-id)\n- [全部模板](#全部模板)"
      : "- [Snapshot](#snapshot)\n- [Invocation example (copy and replace the template ID)](#invocation-example-copy-and-replace-the-template-id)\n- [All templates](#all-templates)",
  );
  out.push("");
  out.push(t ? "## 调用示例(复制后替换模板 ID)" : "## Invocation example (copy and replace the template ID)");
  out.push("");
  out.push("```text");
  if (t) {
    out.push(
      '在 Scientific Figure Library 中搜索模板 "FigureYa1survivalCurve_update"(来源 FigureYa)。',
      "给我看预览和它的输入文件清单,等我确认后再 materialize 到我指定的文件夹。",
      "不要执行绘图代码。",
    );
  } else {
    out.push(
      'Search Scientific Figure Library for the template "FigureYa1survivalCurve_update" (FigureYa provider).',
      "Show me the preview and its input file list; materialize it into the folder I specify only after I confirm.",
      "Do not execute plotting code.",
    );
  }
  out.push("```");
  out.push("");
  out.push(t ? "## 全部模板" : "## All templates");
  out.push("");
  out.push(
    t
      ? "| 模板 ID | 缩略图 | 主要依赖包 | 输入文件 | 说明(节选) | 上游报告 |"
      : "| Template ID | Thumbnail | Packages | Input files | Description (excerpt) | Upstream report |",
  );
  out.push("| --- | --- | --- | --- | --- | --- |");
  out.push(...rows);
  out.push("");
  out.push(
    t
      ? "说明(节选)列截断自上游 `application`/`requirement`/`inputSummary` 字段首行,完整内容以 SFL 的 `figure_library_describe` 输出为准。"
      : 'The "Description (excerpt)" column truncates the first line of the upstream `application`/`requirement`/`inputSummary` fields; use `figure_library_describe` in SFL for the full text.',
  );
  out.push("");
  out.push(
    t
      ? `[返回用户手册目录](../USER_GUIDE.zh-CN.md#4-图型索引按用途) · [返回本页目录](#目录)`
      : `[Back to the user guide](../USER_GUIDE.md#4-figure-index-by-purpose) · [Back to this page's TOC](#table-of-contents)`,
  );
  out.push("");
  return out.join("\n");
}

fs.mkdirSync(outDir, { recursive: true });
const outputs = {
  "open-figure-modules-index.md": buildOfmIndex("en"),
  "open-figure-modules-index.zh-CN.md": buildOfmIndex("zh"),
  "figureya-index.md": buildFigureyaIndex("en"),
  "figureya-index.zh-CN.md": buildFigureyaIndex("zh"),
};
for (const [name, content] of Object.entries(outputs)) {
  fs.writeFileSync(path.join(outDir, name), content, "utf8");
  console.log(`wrote docs/generated/${name} (${content.length} bytes)`);
}
